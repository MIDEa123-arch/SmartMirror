// Creates a private Mosquitto listener, TLS CA/server certificate, ACL and runtime credentials.
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const {spawnSync} = require('node:child_process');
const selfsigned = require('../.runtime/node_modules/selfsigned');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, '.runtime', 'mosquitto');
const certDir = path.join(dir, 'certs');
const confFile = path.join(dir, 'mosquitto.conf');
const settingsFile = path.join(dir, 'smartmirror-mqtt.json');
const caFile = path.join(certDir, 'ca.crt');
const caKeyFile = path.join(certDir, 'ca.key');
const certFile = path.join(certDir, 'server.crt');
const keyFile = path.join(certDir, 'server.key');
const user = 'smartmirror';

function localIPv4() {
  const entries = Object.entries(os.networkInterfaces());
  const all = entries.flatMap(([name, addresses]) => (addresses||[]).filter(x => x && x.family === 'IPv4' && !x.internal).map(x=>({name,address:x.address})));
  const privateAddress = x => /^192\.168\./.test(x) || /^10\./.test(x) || /^172\.(1[6-9]|2\d|3[01])\./.test(x);
  return all.find(x=>/wi-?fi|wireless/i.test(x.name)&&privateAddress(x.address))?.address || all.find(x=>privateAddress(x.address))?.address;
}
function configPath(p) { return p.replace(/\\/g, '/'); }
function run(exe, args, input) {
  const result = spawnSync(exe, args, {input, encoding:'utf8', windowsHide:true});
  if (result.status !== 0) throw new Error(`${path.basename(exe)} failed: ${(result.stderr || result.stdout || '').trim()}`);
}

(async () => {
  const host = process.argv[2] || localIPv4();
  if (!host) throw new Error('No private IPv4 address found. Pass the laptop Wi-Fi address, for example: node scripts/setup-private-mqtt.cjs 192.168.1.20');
  fs.mkdirSync(certDir, {recursive:true});
  fs.mkdirSync(path.join(dir, 'data'), {recursive:true});

  let ca, password;
  if (fs.existsSync(caFile) && fs.existsSync(caKeyFile)) {
    ca = {cert:fs.readFileSync(caFile,'utf8'), private:fs.readFileSync(caKeyFile,'utf8')};
  } else {
    ca = await selfsigned.generate([{name:'commonName',value:'SmartMirror Local MQTT CA'}], {
      keySize:2048, algorithm:'sha256', notAfterDate:new Date(Date.now()+10*365*86400000),
      extensions:[{name:'basicConstraints',cA:true,critical:true},{name:'keyUsage',keyCertSign:true,cRLSign:true,digitalSignature:true,critical:true}]
    });
    fs.writeFileSync(caFile,ca.cert,{mode:0o644});
    fs.writeFileSync(caKeyFile,ca.private,{mode:0o600});
  }
  fs.writeFileSync(path.join(root,'include','mosquitto_local_ca.h'),
    '#pragma once\n// Local MQTT CA. Public trust anchor generated by scripts/setup-private-mqtt.cjs.\n'+
    'constexpr char MOSQUITTO_LOCAL_CA_CERT[] PROGMEM = R"EOF(\n'+ca.cert+'\n)EOF";\n');

  const leaf = await selfsigned.generate([{name:'commonName',value:host}], {
    keySize:2048, algorithm:'sha256', ca:{key:ca.private,cert:ca.cert},
    notAfterDate:new Date(Date.now()+397*86400000),
    // Arduino ESP32's mbed TLS can match a numeric host against a DNS SAN.
    extensions:[{name:'basicConstraints',cA:false,critical:true},{name:'keyUsage',digitalSignature:true,keyEncipherment:true,critical:true},{name:'extKeyUsage',serverAuth:true},{name:'subjectAltName',altNames:[{type:7,ip:host},{type:2,value:host},{type:2,value:'host.wokwi.internal'}]}]
  });
  fs.writeFileSync(certFile,leaf.cert,{mode:0o644});
  fs.writeFileSync(keyFile,leaf.private,{mode:0o600});

  password = fs.existsSync(settingsFile) ? JSON.parse(fs.readFileSync(settingsFile,'utf8')).password : crypto.randomBytes(32).toString('base64url');
  const exe = path.join(dir,'mosquitto_passwd.exe');
  const passFile = path.join(dir,'passwords');
  run(exe,['-c',passFile,user+''],`${password}\n${password}\n`);
  const aclFile = path.join(dir,'acl');
  fs.writeFileSync(aclFile,`user ${user}\ntopic readwrite smartmirror/demo01/#\n`,{encoding:'utf8'});
  const conf = [
    'listener 8883 0.0.0.0',
    'protocol mqtt',
    `certfile ${configPath(certFile)}`,
    `keyfile ${configPath(keyFile)}`,
    'tls_version tlsv1.2',
    'allow_anonymous false',
    `password_file ${configPath(passFile)}`,
    `acl_file ${configPath(aclFile)}`,
    'persistence true',
    `persistence_location ${configPath(path.join(dir,'data'))}/`,
    'log_dest file '+configPath(path.join(dir,'mosquitto.log')),
    'log_type error',
    'log_type warning',
    'log_type notice',
    'log_type information',
    ''
  ].join('\n');
  fs.writeFileSync(confFile,conf);
  const settings={host,port:8883,username:user,password,caFile,caCertificate:ca.cert,configFile:confFile};
  fs.writeFileSync(settingsFile,JSON.stringify(settings,null,2)+'\n');

  console.log(JSON.stringify({host,port:8883,username:user,caFile,configFile:confFile,mode:'user process'},null,2));
})().catch(error=>{console.error(error.stack||error);process.exitCode=1;});
